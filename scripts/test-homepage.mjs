import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const engine=createRequire(import.meta.url)('../static/js/directory-search.js');
const data=JSON.parse(fs.readFileSync(path.join(root,'data/directory-index.json'),'utf8'));
assert.equal(data.count,data.entries.length);
assert.equal(new Set(data.entries.map(r=>r.slug)).size,data.count);
const prepared=engine.prepare(data);
assert.equal(engine.filter(prepared,'ChatGPT','all')[0].slug,'chatgpt');
assert.equal(engine.filter(prepared,'ZZZZ-nothing-matches-123456','all').length,0);
assert.ok(engine.filter(prepared,'writing','free').every(r=>['free','freemium','open-source'].includes(r.pricing)));
assert.ok(engine.prepare({schemaVersion:1,entries:[{slug:'unsafe',path:'javascript:alert(1)'}]}).length===0);
const fixture=engine.prepare({schemaVersion:1,entries:Array.from({length:10000},(_,i)=>({slug:'tool-'+i,path:'/tool/tool-'+i,name:'Writing '+i,category:'Writing',description:'Writing help',pricing:i%2?'freemium':'paid'}))});
assert.equal(engine.filter(fixture,'writing','all').length,10000);
assert.equal(engine.filter(fixture,'writing','free').length,5000);
assert.equal(engine.filter(fixture,'writing','all').slice(24,48).length,24);
const homepage=fs.readFileSync(path.join(root,'index.html'),'utf8');
assert.ok(!homepage.includes('src="/static/js/main.'));
assert.ok(!homepage.split('</nav>')[0].includes('/sports-research/'));
assert.match(homepage,/<footer[\s\S]*href="\/sports-research\/"/);
assert.match(fs.readFileSync(path.join(root,'scripts/generate-seo.mjs'),'utf8'),/baseTemplate = fs.readFileSync\(path.join\(root, "app.html"\)/);
for(const r of data.entries) assert.ok(fs.existsSync(path.join(root,r.path,'index.html')),`Missing profile ${r.path}`);
console.log(`Homepage checks passed: ${data.count} real listings, safe profile paths, plan filtering, 10k search fixture, and separate SEO shell.`);
